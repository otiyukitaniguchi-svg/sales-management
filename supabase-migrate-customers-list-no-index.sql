-- ============================================================
-- リスト読み込みをさらに高速化: customersテーブルの複合インデックス
--
-- リスト読み込みは customers を list_slug で絞り込んでno順に並べる
-- (WHERE list_slug = ... ORDER BY no)。今はlist_slugとnoそれぞれ単独の
-- インデックスしかないため、絞り込んだ後に毎回並び替え(ソート)が
-- 発生していた。(list_slug, no)の複合インデックスを追加すると、
-- 絞り込みと並び替えを両方インデックスだけで済ませられるようになる。
--
-- 実行方法: Supabaseダッシュボード → SQL Editor に全文貼り付けて実行。
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_customers_list_slug_no ON customers(list_slug, no);

-- ============================================================
-- 完了メッセージ
-- ============================================================
DO $$
BEGIN
  RAISE NOTICE '✅ customers(list_slug, no)の複合インデックスを作成しました。';
END $$;
